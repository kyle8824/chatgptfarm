import assert from 'node:assert/strict';
import {createWorld} from '../engine/core.js';
import {prepare} from './elapsed.mjs';
import {expandFrontier,householdWorld} from './frontier.mjs';
import {reorganizeLandscape} from './landscape-migration.mjs';
import {findMaterialSource} from './settlement.mjs';
import {knownPlace} from './frontier-knowledge.mjs';
import {treeUnits} from './holdings.mjs';
const w=prepare(createWorld());expandFrontier(w);reorganizeLandscape(w);const a=w.agents[0];
a.landmarks=Object.fromEntries(w.settlement.trees.map(t=>[t.id,{seenAt:0,position:t.position}]));a.inventory.boundSharpTool=1;
const view=householdWorld(w,a),before=JSON.stringify(w),batches=w.wood.batches;
const expected=w.settlement.trees.filter(t=>knownPlace(view,a,t)&&treeUnits(view,t)>0&&(a.inventory.boundSharpTool>0||!(t.handGathered>=1))&&Math.hypot(a.coordinates.x-t.position.x,a.coordinates.y-t.position.y)<=45).map(t=>t.id).sort();
let visits=0;w.wood.batches=new Proxy(batches,{get(t,k,r){if(typeof k==='string'&&/^\d+$/.test(k))visits++;return Reflect.get(t,k,r);}});
const start=performance.now(),sources=findMaterialSource(view,a,'timber'),ms=performance.now()-start;
assert.deepEqual(sources.filter(s=>s.treeId).map(s=>s.treeId).sort(),expected,'optimization preserves all finite, known, local timber sources');
assert(visits<batches.length*3,`material search read ${visits} batch entries for ${batches.length} batches: avoid a full ledger scan per known tree`);
w.wood.batches=batches;assert.equal(JSON.stringify(w),before,'a source query does not mutate supplies or knowledge');
const tree=w.settlement.trees.find(t=>expected.includes(t.id));tree.handGathered=1;a.inventory.boundSharpTool=0;
assert(!findMaterialSource(view,a,'timber').some(s=>s.treeId===tree.id),'hand gathering remains finite');
a.inventory.boundSharpTool=1;const stock=batches.filter(b=>b.holder.kind==='ground'&&b.holder.id===tree.id);
for(const b of stock)b.holder={kind:'stored',id:'isolated-depleted-tree-stock'};
assert(!findMaterialSource(view,a,'timber').some(s=>s.treeId===tree.id),'wood moved off the tree is not still harvestable');
console.log(JSON.stringify({result:'PASS linear material search, identical source choices, pure read, finite hand gathering and depleted timber',trees:w.settlement.trees.length,batches:batches.length,visits,searchMs:Math.round(ms)}));
