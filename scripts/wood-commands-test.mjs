import assert from 'node:assert/strict';
import fs from 'node:fs';
import {importLegacyWood,totals,projectWoodCounts,applyWoodCommand,reconcileLegacyWoodEntities} from '../engine/wood-materials.js';
const source={day:19,hour:14,resources:{dryWood:3,wetWood:2},agents:[{id:'mara',inventory:{dryWood:1,wetWood:3}},{id:'ivo',inventory:{dryWood:0,wetWood:0}}],worldModel:{objects:[{id:'branch-1',physical:{wood:true},state:{carried:true,inventoryKey:'wetWood',massKg:4},carrierId:'mara'}]}};
const ledger=importLegacyWood(source),initial=totals(ledger);
reconcileLegacyWoodEntities(source,ledger);
assert.deepEqual(totals(ledger),initial,'Entity alias cannot create material');
const linked=ledger.batches.find(b=>b.entityIds?.includes('branch-1'));
assert.equal(linked.units,1);assert.equal(linked.legacyEntityMassKg,4);
const once=JSON.stringify(ledger);reconcileLegacyWoodEntities(source,ledger);assert.equal(JSON.stringify(ledger),once);
const impossible=structuredClone(source);impossible.worldModel.objects[0].carrierId='unknown';
assert.throws(()=>reconcileLegacyWoodEntities(impossible,importLegacyWood(source)),/Unreconciled/);
const command={operationId:'gather-1',from:{kind:'ground',id:'log'},to:{kind:'carried',id:'ivo'},quantity:2,category:'dryWood',reason:'gather'};
const gathered=applyWoodCommand(ledger,command);
assert.equal(projectWoodCounts(ledger,command.from).dryWood,1);
assert.equal(projectWoodCounts(ledger,command.to).dryWood,2);
assert.deepEqual(totals(ledger),initial);
assert.deepEqual(applyWoodCommand(ledger,command),gathered);
assert.throws(()=>applyWoodCommand(ledger,{...command,quantity:1}),/Conflicting/);
const before=JSON.stringify(ledger);
assert.throws(()=>applyWoodCommand(ledger,{...command,operationId:'gather-2',quantity:2}),/Insufficient/);
assert.equal(JSON.stringify(ledger),before,'Last-portion contention cannot partially transfer');
const cut={operationId:'cut-1',from:{kind:'carried',id:'mara'},to:{kind:'carried',id:'mara'},quantity:1,category:'wetWood',outputForm:'pole',reason:'shape branch'};
const result=applyWoodCommand(ledger,cut),pole=ledger.batches.find(b=>b.id===result.outputs[0]);
assert.equal(pole.form,'pole');assert(pole.waterKg/pole.dryKg>.24,'Shaping wet wood cannot dry it');
assert.equal(projectWoodCounts(ledger,cut.from).wetWood,2);
assert.deepEqual(totals(ledger),initial,'A pole retains its material instead of becoming a sink');
applyWoodCommand(ledger,{operationId:'build-1',from:command.to,to:{kind:'stored',id:'shelter-1'},quantity:1,category:'dryWood',outputForm:'shelter-component',reason:'place in shelter'});
assert.deepEqual(totals(ledger),initial,'Construction preserves wood in output account');
applyWoodCommand(ledger,{operationId:'burn-1',mode:'burn',from:command.to,quantity:1,category:'dryWood',reason:'fuel combustion'});
assert.equal(totals(ledger).dryKg+ledger.sinks.reduce((n,s)=>n+s.dryKg,0),initial.dryKg);
assert.throws(()=>applyWoodCommand(ledger,{operationId:'burn-wet',mode:'burn',from:cut.from,quantity:1,category:'wetWood',reason:'fuel combustion'}),/usable/);
const saved=fs.readFileSync('world/state.json','utf8'),world=JSON.parse(saved),proposed=importLegacyWood(world);
reconcileLegacyWoodEntities(world,proposed);
for(const a of world.agents)assert.deepEqual(projectWoodCounts(proposed,{kind:'carried',id:a.id}),{dryWood:a.inventory.dryWood,wetWood:a.inventory.wetWood});
assert.equal(fs.readFileSync('world/state.json','utf8'),saved);
console.log('PASS transactional gathering, competing harvest, retry conflicts, wet pole, construction accounts, burning, entity reconciliation, saved-state import');
