import assert from 'node:assert/strict';
import {importLegacyWood,totals,projectWoodCounts,transferWood,integrateWood,consumeWood} from '../engine/wood-materials.js';
const source={day:19,hour:14,resources:{dryWood:0,wetWood:0},agents:[
  {id:'agent-mara',inventory:{dryWood:1,wetWood:58}},
  {id:'agent-ivo',inventory:{dryWood:1,wetWood:65}}]};
const original=JSON.stringify(source),ledger=importLegacyWood(source),at=ledger.lastHour;
assert.equal(JSON.stringify(source),original);
assert.deepEqual(importLegacyWood(source),ledger,'Import is deterministic and has no elapsed effects');
assert.equal(totals(ledger).units,125);
for(const a of source.agents)assert.deepEqual(projectWoodCounts(ledger,{kind:'carried',id:a.id}),a.inventory);
const before=totals(ledger),wet=ledger.batches.find(b=>b.origin.category==='wetWood');
const moved=transferWood(ledger,wet.id,10,{kind:'stored',id:'camp-cover'});
assert.deepEqual(totals(ledger),before);
assert.equal(ledger.batches.find(b=>b.id===moved).lineage[0],wet.id);
const snapshot=JSON.stringify(ledger);
assert.throws(()=>transferWood(ledger,wet.id,1000,{kind:'ground',id:'log'}));
assert.equal(JSON.stringify(ledger),snapshot,'Failed transfer is atomic');
const conditions=h=>({temperatureC:20,humidity:.5,airflow:1,raining:true,covered:h.kind==='stored'});
const oldDry=totals(ledger).dryKg;
integrateWood(ledger,at+48,conditions);
assert.equal(totals(ledger).dryKg,oldDry,'Drying/rewetting cannot change wood mass');
assert.equal(projectWoodCounts(ledger,{kind:'stored',id:'camp-cover'}).dryWood,10,'Covered damp wood becomes usable with elapsed time');
assert.equal(projectWoodCounts(ledger,{kind:'carried',id:'agent-ivo'}).dryWood,0,'Uncovered rain rewets carried fuel');
const once=JSON.stringify(ledger);integrateWood(ledger,at+48,conditions);assert.equal(JSON.stringify(ledger),once);
const restored=JSON.parse(once);integrateWood(restored,at+48,conditions);assert.deepEqual(restored,ledger);
const single=importLegacyWood(source),split=importLegacyWood(source);
const dry=()=>({temperatureC:18,humidity:.6,airflow:1.2,raining:false,covered:false});
integrateWood(single,at+24,dry);
for(let i=1;i<=48;i++)integrateWood(split,at+i/2,dry);
assert(Math.abs(totals(single).waterKg-totals(split).waterKg)<1e-9,'Equivalent elapsed-time partitions agree');
const unchanged=JSON.stringify(split);let calls=0;
assert.throws(()=>integrateWood(split,at+25,h=>++calls===2?{}:dry(h)));
assert.equal(JSON.stringify(split),unchanged,'Invalid exposure cannot partially advance material');
const batch=single.batches[0];const result=consumeWood(single,batch.id,1,{reason:'test combustion',operationId:'op-1'});
assert.deepEqual(consumeWood(single,batch.id,1,{reason:'test combustion',operationId:'op-1'}),result);
assert.throws(()=>consumeWood(single,batch.id,2,{reason:'test combustion',operationId:'op-1'}),/Conflicting/);
assert(Math.abs(totals(single).dryKg+single.sinks.reduce((n,s)=>n+s.dryKg,0)-single.initialDryKg)<1e-9);
assert(Math.abs(totals(single).waterKg+single.sinks.reduce((n,s)=>n+s.waterKg,0)-single.initialWaterKg-single.environmentWaterExchangeKg)<1e-9);
console.log('PASS legacy owners/quantities, conserved transfers, covered drying, rain rewetting, retry/reload, fractional time, atomic errors, consumption accounting');
